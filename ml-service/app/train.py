"""
Train + evaluate the HireHub ML models.
  python -m app.train                       # synthetic resumes
  python -m app.train --csv Resume.csv      # real Kaggle dataset (columns: Category, Resume)

Produces in artifacts/: classifier.joblib, embedder.joblib, metrics.json
Models:
  1. Resume -> role classifier: TF-IDF(1-2 grams) + Logistic Regression (compared with NB, Linear SVM, majority baseline)
  2. Embedder: TF-IDF -> TruncatedSVD (LSA) -> L2-normalise.  Retrieval is evaluated against a plain TF-IDF baseline.
"""
import argparse, json, time
import numpy as np, pandas as pd, joblib
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.decomposition import TruncatedSVD
from sklearn.linear_model import LogisticRegression
from sklearn.naive_bayes import MultinomialNB
from sklearn.svm import LinearSVC
from sklearn.dummy import DummyClassifier
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import Normalizer
from sklearn.model_selection import train_test_split, cross_val_score, StratifiedKFold
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix
from .config import ARTIFACTS, JOBS_SEED, TOKEN_PATTERN
from . import synth

def tfidf(**kw):
    return TfidfVectorizer(lowercase=True, token_pattern=TOKEN_PATTERN, ngram_range=(1, 2), sublinear_tf=True, min_df=2, **kw)

def job_text(j):
    return " ".join([j["title"], " ".join(j.get("skills", [])), j.get("description", ""), j.get("requirements", "") or ""])

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--csv"); ap.add_argument("--n", type=int, default=250)
    args = ap.parse_args(); t0 = time.time()

    if args.csv:
        df = pd.read_csv(args.csv); df = df.rename(columns={"Category": "role", "Resume": "text"})[["text", "role"]].dropna()
        source = f"real dataset: {args.csv}"
    else:
        rows = synth.generate(args.n); df = pd.DataFrame(rows, columns=["text", "role"]); source = "synthetic (noisy, generated by app/synth.py)"
    X, y = df["text"].tolist(), df["role"].tolist()
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)

    candidates = {
        "Majority baseline": DummyClassifier(strategy="most_frequent"),
        "Naive Bayes": MultinomialNB(alpha=0.1),
        "Linear SVM": LinearSVC(C=1.0),
        "Logistic Regression": LogisticRegression(C=10, max_iter=2000),
    }
    comparison, fitted = {}, {}
    cv = StratifiedKFold(5, shuffle=True, random_state=1)
    for name, clf in candidates.items():
        pipe = make_pipeline(tfidf(), clf)
        cvs = cross_val_score(pipe, Xtr, ytr, cv=cv, scoring="f1_macro")
        pipe.fit(Xtr, ytr); pred = pipe.predict(Xte)
        comparison[name] = dict(cv_macro_f1=round(float(cvs.mean()), 4), cv_std=round(float(cvs.std()), 4),
                                test_accuracy=round(accuracy_score(yte, pred), 4), test_macro_f1=round(f1_score(yte, pred, average="macro"), 4))
        fitted[name] = pipe; print(f"{name:22s}", comparison[name])

    best = "Logistic Regression"; clf = fitted[best]; pred = clf.predict(Xte)
    labels = sorted(set(y))
    report = classification_report(yte, pred, output_dict=True, zero_division=0)
    cm = confusion_matrix(yte, pred, labels=labels)
    joblib.dump(clf, ARTIFACTS / "classifier.joblib")

    # ---- embeddings + retrieval evaluation --------------------------------------------------
    jobs = json.load(open(JOBS_SEED, encoding="utf-8"))
    jtexts = [job_text(j) for j in jobs]
    emb = make_pipeline(tfidf(), TruncatedSVD(n_components=96, random_state=0), Normalizer(copy=False))
    emb.fit(Xtr + jtexts); joblib.dump(emb, ARTIFACTS / "embedder.joblib")
    role_of = lambda j: j["title"].replace("Intern – ", "")
    jroles = [role_of(j) for j in jobs]

    def hit_rate(sim, k):  # does a job of the resume's true role appear in the top-k?
        return float(np.mean([any(jroles[i] == yt for i in np.argsort(-sim[r])[:k]) for r, yt in enumerate(yte)]))
    Q = emb.transform(Xte); J = emb.transform(jtexts); sim_lsa = Q @ J.T
    base = tfidf().fit(Xtr + jtexts); sim_tfidf = (base.transform(Xte) @ base.transform(jtexts).T).toarray()
    retrieval = {"embeddings_LSA": {f"top{k}": round(hit_rate(sim_lsa, k), 4) for k in (1, 3, 5)},
                 "tfidf_baseline": {f"top{k}": round(hit_rate(sim_tfidf, k), 4) for k in (1, 3, 5)}}
    print("retrieval", retrieval)

    metrics = dict(trained_at=time.strftime("%Y-%m-%d %H:%M:%S"), seconds=round(time.time() - t0, 1), data_source=source,
        n_train=len(Xtr), n_test=len(Xte), classes=labels, chosen_model=best,
        accuracy=round(accuracy_score(yte, pred), 4), macro_f1=round(f1_score(yte, pred, average="macro"), 4),
        model_comparison=comparison,
        per_class={c: {k: round(report[c][k], 3) for k in ("precision", "recall", "f1-score")} | {"support": int(report[c]["support"])} for c in labels},
        confusion_matrix=dict(labels=labels, matrix=cm.tolist()), retrieval=retrieval,
        note="Metrics on a held-out 20% split. If source is synthetic, treat numbers as a pipeline sanity check, not real-world accuracy.")
    json.dump(metrics, open(ARTIFACTS / "metrics.json", "w"), indent=1)
    print(f"\nSaved artifacts -> {ARTIFACTS}  | accuracy={metrics['accuracy']} macro_f1={metrics['macro_f1']}")

if __name__ == "__main__":
    main()
